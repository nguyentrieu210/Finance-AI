-- Synthetic-only pipeline persistence. No CLEAN release, actual user file or runtime grant.
ALTER TABLE finance.outbox DROP CONSTRAINT outbox_event_type_check,
 ADD CONSTRAINT outbox_event_type_check CHECK(event_type IN ('ORG_UNIT_CREATED','ORG_UNIT_UPDATED','DOSSIER_CREATED','DOCUMENT_INTENT_CREATED','SYNTHETIC_OCR_REQUESTED'));
CREATE TABLE finance.ocr_run (
 tenant_id uuid NOT NULL, company_id uuid NOT NULL,id uuid NOT NULL,
 document_id uuid NOT NULL,revision_id uuid NOT NULL,source_digest bytea NOT NULL CHECK(octet_length(source_digest)=32),
 generation bigint NOT NULL CHECK(generation>0),job_id uuid NOT NULL,fence bigint NOT NULL CHECK(fence BETWEEN 1 AND 3),
 engine text NOT NULL CHECK(engine='TESSERACT_SYNTHETIC'),model_digest bytea NOT NULL CHECK(octet_length(model_digest)=32),
 config_digest bytea NOT NULL CHECK(octet_length(config_digest)=32),
 page_count integer NOT NULL CHECK(page_count BETWEEN 1 AND 200),
 result_digest bytea NOT NULL CHECK(octet_length(result_digest)=32),
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 PRIMARY KEY(tenant_id,company_id,id), UNIQUE(tenant_id,company_id,job_id,fence),
 FOREIGN KEY(tenant_id,company_id,document_id) REFERENCES finance.document_ref(tenant_id,company_id,id),
 FOREIGN KEY(tenant_id,company_id,job_id,fence) REFERENCES finance.job_attempt(tenant_id,company_id,job_id,fence)
);
CREATE TABLE finance.evidence (
 tenant_id uuid NOT NULL,company_id uuid NOT NULL,id uuid NOT NULL,ocr_run_id uuid NOT NULL,
 page integer NOT NULL CHECK(page BETWEEN 1 AND 200),block_index integer NOT NULL CHECK(block_index BETWEEN 0 AND 9999),
 x0 integer NOT NULL,y0 integer NOT NULL,x1 integer NOT NULL,y1 integer NOT NULL,
 excerpt text NOT NULL CHECK(octet_length(excerpt) BETWEEN 1 AND 4096 AND btrim(excerpt)<>''),
 confidence integer CHECK(confidence BETWEEN 0 AND 10000),
 PRIMARY KEY(tenant_id,company_id,id),UNIQUE(tenant_id,company_id,ocr_run_id,page,block_index),
 FOREIGN KEY(tenant_id,company_id,ocr_run_id) REFERENCES finance.ocr_run(tenant_id,company_id,id),
 CHECK(x0>=0 AND y0>=0 AND x1>x0 AND y1>y0 AND x1<=1000000 AND y1<=1000000)
);
CREATE TABLE finance.extraction_run (
 tenant_id uuid NOT NULL,company_id uuid NOT NULL,id uuid NOT NULL,ocr_run_id uuid NOT NULL,
 schema_version text NOT NULL CHECK(schema_version='synthetic.rows.v1'),
 PRIMARY KEY(tenant_id,company_id,id), UNIQUE(tenant_id,company_id,ocr_run_id),
 FOREIGN KEY(tenant_id,company_id,ocr_run_id) REFERENCES finance.ocr_run(tenant_id,company_id,id)
);
CREATE TABLE finance.extracted_field (
 tenant_id uuid NOT NULL,company_id uuid NOT NULL,run_id uuid NOT NULL,field_path text NOT NULL,
 state text NOT NULL CHECK(state IN ('UNKNOWN','INVALID','AMBIGUOUS','CANDIDATE')),
 normalized_value text, source_page integer, block_indexes integer[] NOT NULL,
 PRIMARY KEY(tenant_id,company_id,run_id,field_path),
 FOREIGN KEY(tenant_id,company_id,run_id) REFERENCES finance.extraction_run(tenant_id,company_id,id),
 CHECK(field_path IN ('invoice.number','invoice.date','invoice.supplier','invoice.net','invoice.tax','invoice.total')),
 CHECK((state='CANDIDATE')=(normalized_value IS NOT NULL)),
 CHECK((source_page IS NULL AND cardinality(block_indexes)=0) OR (source_page BETWEEN 1 AND 200 AND cardinality(block_indexes) BETWEEN 1 AND 16)),
 CHECK(normalized_value IS NULL OR octet_length(normalized_value) BETWEEN 1 AND 512)
);
