ALTER TABLE finance.extraction_run ENABLE ROW LEVEL SECURITY;
ALTER TABLE finance.extraction_run FORCE ROW LEVEL SECURITY;
CREATE TRIGGER extraction_run_immutable BEFORE UPDATE OR DELETE ON finance.extraction_run FOR EACH ROW EXECUTE FUNCTION finance.reject_synthetic_document_mutation();
ALTER TABLE finance.extracted_field ENABLE ROW LEVEL SECURITY;
